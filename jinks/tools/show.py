"""show.py START END [COLS]: print the traced listing jinks/disasm/src/f7.asm between two addresses,
compact (label lines kept, instruction text + address), COLS instructions per line (default 3).
Reads only; the listing is regenerated by regen.py."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "disasm", "src", "f7.asm")
lo, hi = int(sys.argv[1], 16), int(sys.argv[2], 16)
cols = int(sys.argv[3]) if len(sys.argv) > 3 else 3
pat = re.compile(r";\s*([0-9A-F]{4})[: ]")
out, row, on = [], [], False
pend = []
for ln in open(SRC, encoding="utf-8", errors="replace"):
    s = ln.rstrip()
    m = pat.search(s)
    if not m:
        if on and s and not s.startswith("; xrefs") and not s.startswith(";"):
            pend.append(s.strip())
        elif not on and s and not s.startswith(";"):
            pend = [s.strip()]
        continue
    a = int(m.group(1), 16)
    if a < lo:
        pend = []
        continue
    if a > hi:
        break
    on = True
    code = s.split(";")[0].strip()
    code = re.sub(r"\s+", " ", code)
    if pend:
        if row:
            out.append("  |  ".join(row))
            row = []
        out.append(" ".join(pend))
        pend = []
    if code.startswith(".byte"):
        if row:
            out.append("  |  ".join(row))
            row = []
        out.append("%04X: %s" % (a, code))
        continue
    row.append("%04X %-22s" % (a, code))
    if len(row) == cols:
        out.append("  |  ".join(row))
        row = []
if row:
    out.append("  |  ".join(row))
print("\n".join(out))
